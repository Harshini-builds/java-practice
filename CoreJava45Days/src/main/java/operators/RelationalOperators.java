package operators;

/* Relational Operators used to compare two values always returns true or false 
 * 
 */
public class RelationalOperators {

	public static void main(String[] args) {
	int n1=10;
	int n2=20;
	System.out.println("Less than operator :"+(n1<n2));
	System.out.println("Greater than operator :"+(n1>n2));
	System.out.println("Less than or equals to operator :"+(n1<=n2));
	System.out.println("Greater than or equals to operator :"+(n1>=n2));
	System.out.println("Equals operator :"+(n1==n2));
	System.out.println("Not Equals operator : "+(n1!=n2));
	
	}

}
