package operators;

/* Ternary operator is short form of if-else statement
 * 
 */

public class TernaryOperators {

	public static void main(String[] args) {
	 int a=10;
	 int b=20;
	 int largest=(a<b)?a:b;//(condition)? expression1:expression2
	 System.out.println("====================================");
	 System.out.println("Ternary Or Conditional Operator");
	 System.out.println("====================================");
	 System.out.println("Largest number :"+largest);

	}

}
